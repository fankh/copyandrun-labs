#!/bin/sh
# 사용: sh dirtypipe-check.sh [커널 버전]   (버전을 생략하면 uname -r)
# CVE-2022-0847(Dirty Pipe)의 NVD 영향 범위에 커널 버전이 들어가는지 본다.
#   5.8 이상 5.10.102 미만, 5.15 이상 5.15.25 미만, 5.16 이상 5.16.11 미만
V="${1:-$(uname -r)}"
B=$(echo "$V" | sed -n 's/^\([0-9]*\.[0-9]*\.[0-9]*\).*/\1/p')
[ -n "$B" ] || { echo "버전을 읽지 못함: $V"; exit 1; }

lt() { [ "$1" != "$2" ] && [ "$(printf '%s\n%s\n' "$1" "$2" | sort -V | sed -n '1p')" = "$1" ]; }
ge() { ! lt "$1" "$2"; }
range() { ge "$B" "$1" && lt "$B" "$2"; }

if range 5.8.0 5.10.102 || range 5.15.0 5.15.25 || range 5.16.0 5.16.11; then
  echo "커널 $V: NVD 영향 범위 안 (업데이트 필요)"
elif lt "$B" 5.8.0; then
  echo "커널 $V: 5.8 미만이라 범위 밖"
else
  echo "커널 $V: NVD 영향 범위 밖 (배포판 커널은 번호가 달라도 수정을 반영하므로 보안 공지로 확인)"
fi
